/* =============================================================================
   Self-checks
   ============================================================================= */

-- 1. Every material must have content, and the recorded size must match it
IF EXISTS (
    SELECT 1 FROM dbo.Material m
    LEFT JOIN dbo.MaterialFile f ON f.MaterialId = m.MaterialId
    WHERE f.MaterialId IS NULL OR DATALENGTH(f.Content) <> m.FileSizeBytes
)
BEGIN
    THROW 50010, N'[03_seed] FAILED: a material is missing content or has a wrong FileSizeBytes.', 1;
END

-- 2. student01's CSD201 retake must be failed and excluded from the GPA
IF NOT EXISTS (
    SELECT 1 FROM dbo.Enrollment e
    JOIN dbo.Student s ON s.StudentId = e.StudentId
    JOIN dbo.Course  c ON c.CourseId  = e.CourseId
    WHERE s.StudentCode = N'SE170001' AND c.CourseCode = N'CSD201'
      AND e.Status = N'Failed' AND e.IsCounted = 0
)
BEGIN
    THROW 50011, N'[03_seed] FAILED: the CSD201 retake case for SE170001 is in the wrong state.', 1;
END

-- 3. No student may have the same course counted toward the GPA twice
IF EXISTS (
    SELECT StudentId, CourseId FROM dbo.Enrollment
    WHERE IsCounted = 1
    GROUP BY StudentId, CourseId HAVING COUNT(*) > 1
)
BEGIN
    THROW 50012, N'[03_seed] FAILED: a course is counted toward the GPA more than once.', 1;
END

-- 4. Courses in the current term must still be in progress
IF EXISTS (
    SELECT 1 FROM dbo.Enrollment e
    JOIN dbo.Semester s ON s.SemesterId = e.SemesterId
    WHERE s.IsCurrent = 1 AND e.Status <> N'Studying'
)
BEGIN
    THROW 50013, N'[03_seed] FAILED: a course in the current term has already been settled.', 1;
END

-- 5. Every completed course must carry a letter grade
IF EXISTS (
    SELECT 1 FROM dbo.Enrollment
    WHERE Status IN (N'Passed', N'Failed') AND (FinalScore IS NULL OR LetterGrade IS NULL)
)
BEGIN
    THROW 50014, N'[03_seed] FAILED: a completed course is missing its final score.', 1;
END
