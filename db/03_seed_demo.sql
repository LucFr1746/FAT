/* -----------------------------------------------------------------------------
   Grade - component scores

   Deterministic formula:
     base  = 5.8 + ((StudentId * 7 + CourseId * 13) % 38) / 10.0   -> 5.8 .. 9.5
     score = base + (((AssessmentId * 3 + EnrollmentId * 5) % 11) - 5) / 10.0
   i.e. a +/- 0.5 spread around the base, then clamped to [0, 10].
   ----------------------------------------------------------------------------- */

DECLARE @CurrentOrder INT = (SELECT DisplayOrder FROM dbo.Semester WHERE IsCurrent = 1);

-- (a) COMPLETED terms: every component has a score
INSERT INTO dbo.Grade (EnrollmentId, AssessmentId, Score)
SELECT
    e.EnrollmentId,
    a.AssessmentId,
    CAST(
        CASE
            WHEN raw.Val < 0  THEN 0
            WHEN raw.Val > 10 THEN 10
            ELSE raw.Val
        END AS DECIMAL(4,2))
FROM dbo.Enrollment e
JOIN dbo.Semester   s ON s.SemesterId = e.SemesterId
JOIN dbo.Assessment a ON a.CourseId   = e.CourseId
CROSS APPLY (
    SELECT Val =
        (5.8 + ((e.StudentId * 7 + e.CourseId * 13) % 38) / 10.0)
      + (((a.AssessmentId * 3 + e.EnrollmentId * 5) % 11) - 5) / 10.0
) AS raw
WHERE s.DisplayOrder < @CurrentOrder;

-- (b) CURRENT term: continuous-assessment marks only, no final exam yet
--     so FinalScore stays NULL and Status stays 'Studying'. This is the real
--     code path of the "courses in progress" screen, so it needs real data.
INSERT INTO dbo.Grade (EnrollmentId, AssessmentId, Score)
SELECT
    e.EnrollmentId,
    a.AssessmentId,
    CAST(
        CASE
            WHEN raw.Val < 0  THEN 0
            WHEN raw.Val > 10 THEN 10
            ELSE raw.Val
        END AS DECIMAL(4,2))
FROM dbo.Enrollment e
JOIN dbo.Semester   s ON s.SemesterId = e.SemesterId
JOIN dbo.Assessment a ON a.CourseId   = e.CourseId
CROSS APPLY (
    SELECT Val =
        (5.8 + ((e.StudentId * 7 + e.CourseId * 13) % 38) / 10.0)
      + (((a.AssessmentId * 3 + e.EnrollmentId * 5) % 11) - 5) / 10.0
) AS raw
WHERE s.DisplayOrder = @CurrentOrder
  AND a.Name IN (N'Assignment', N'Progress Test', N'Supervisor Evaluation');
GO

/* -----------------------------------------------------------------------------
   Force student01 to FAIL CSD201 on the first attempt (FA24)

   A final exam score of 3.0 is below MinScoreToPass 4.0, which fails the course
   under the regulation even though the weighted total might still reach 5.0.
   This is the "failed on a component" test case.
   ----------------------------------------------------------------------------- */
UPDATE g
SET Score = CASE WHEN a.Name = N'Final Exam' THEN 3.00 ELSE 4.50 END
FROM dbo.Grade g
JOIN dbo.Assessment a ON a.AssessmentId = g.AssessmentId
JOIN dbo.Enrollment e ON e.EnrollmentId = g.EnrollmentId
